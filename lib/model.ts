// Token Radar, model radar-2: the sealed DefiLlama snapshot in, one ranked board out.
//
// The board ranks every protocol the snapshot records as pre-token once the
// watchlist's own exclusions are applied to the whole file: no token on
// record, not a wrapped, staked or bridged product of a token that already
// trades, not a versioned pool, not an exchange. That is 198 rows here: the
// 40 watchlist protocols plus 158 more below the $50M floor. A protocol
// whose token already trades is never ranked; the live set is shown apart,
// with the market cap the market itself gives it.
//
// Implied value is one function of the snapshot's own figures, the same for
// every row, no name ever special-cased:
//
//   base      = tvl_usd x 0.25
//   growth    = clamp(change_7d, -50, 100) per cent
//   growthMult   = 1 + growth / 100 x 0.6          (0.70 to 1.60)
//   maturity  = 0.70 + min(age_days, 1095) / 1095 x 0.30   (0.70 to 1.00)
//   breadth   = 1 + 0.02 x min(chains - 1, 5)      (1.00 to 1.10)
//   implied   = max(1, round(base x growthMult x maturity x breadth))
//
// Why these four: TVL is the size of the economy a token would tax; seven-day
// growth is the only momentum the snapshot carries, weighted so a hot week
// lifts a row but cannot carry it alone; age is how long a protocol has run
// with no token, the best record of staying power, and it saturates at three
// years so an old protocol cannot win on age alone; chain breadth is a small
// credit for a protocol that already serves more than one chain. A missing
// seven-day change scores as zero growth, and an unknown listing date scores
// as 365 days, so no row is dropped for a gap in the record.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_per_chain: number;
  breadth_max_chains: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.25,
  growth_weight: 0.6,
  growth_floor: -50,
  growth_cap: 100,
  maturity_floor: 0.7,
  maturity_range: 0.3,
  maturity_days: 1095,
  unknown_age_days: 365,
  breadth_per_chain: 0.02,
  breadth_max_chains: 5,
};

export const MODEL_VERSION = 'radar-2';

